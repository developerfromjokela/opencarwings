import decimal
from typing import Dict, Any, Tuple

from tculink.gdc_proto import WH_PER_GID_GEN1
from tculink.gdc_proto.acp245 import parser, composer


def parse_auth_ev_pload(acp_encoded_data: bytes) -> Tuple[dict, int]:
    result: Dict[str, Any] = {}
    offset = 0

    app_header, consumed = parser.decode_app_header(acp_encoded_data, offset)
    result["app_header"] = app_header
    offset += consumed

    version, consumed = parser.parse_version_ficosa(acp_encoded_data, offset)
    result["version"] = version
    offset += consumed

    veh_desc, consumed = parser.decode_veh_desc(acp_encoded_data, offset)
    result["veh_desc"] = veh_desc
    offset += consumed

    # Dest ID = specific function / program in TCU
    dest_id = parser.get_single_byte(acp_encoded_data, offset)
    result["dest_id"] = dest_id
    offset += 1

    # Random request identifier generated by server, "session token" of sorts
    source_id = parser.get_single_byte(acp_encoded_data, offset)
    offset += 1
    result["source_id"] = source_id

    timestamp, consumed = parser.decode_timestamp(acp_encoded_data, offset)
    result["timestamp"] = timestamp
    offset += consumed

    auth, consumed = parser.decode_acp_auth(acp_encoded_data, offset)
    offset += consumed
    result["auth"] = auth

    gps, consumed = parser.decode_gps_position(acp_encoded_data, offset)
    offset += consumed
    result["position"] = gps

    return result, offset

