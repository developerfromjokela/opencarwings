def parse_ev_info(data: bytes, offset: int) -> Tuple[dict, int]:
    d, all_li = parser._decode_ie_element(data, offset, 0, parser.IE_Element())
    d = d["value"]
    if len(d) < 0x16:
        raise Exception("Not enough bytes in EV data")
    # Format Doc: EVInfo.ods @ nissan-leaf-tcu repo

    pluggedin = (d[0] & 0b00001001) == 9
    charging = ((d[0] & 0b01000000) >> 6) == 1
    ignition = ((d[0] & 0b00100000) >> 5) == 1
    # TODO quickcharge
    quick_charging = False
    finish_flag = (d[0] & 0b10000000) > 0
    acstate = ((d[0] & 0b00000010) >> 1) == 1

    chargebars = 0
    chgbar_multiplier = (d[9] & 0b11111000) >> 3
    if 0x1F > chgbar_multiplier > 0:
        chargebars = (((d[9] & 0b00000111) << 3) | ((d[10] & 0b11100000) >> 5)) / chgbar_multiplier

    drive_status = (d[4] & 0b11111000) >> 3

    soh = ((d[6] & 0b00111111) << 1) | ((d[7] & 0b10000000) >> 7)

    soc = (((d[7] & 0b01111111) << 3) | ((d[8] & 0b11100000) >> 3))/10.0
    soc_display_int = d[11]
    soc_display = ((d[17] << 4) | ((d[18] & 0b11110000) >> 4))
    if soc_display == 0:
        soc_display = soc_display_int
    else:
        soc_display = soc_display / 8.00

    gids = (d[5] << 2) | ((d[6] & 0b11000000) >> 6)

    acoff = (d[19] << 2) | ((d[20] & 0b11000000) >> 6)
    acon = ((d[20] & 0b00111111) << 4) | ((d[21] & 0b11110000) >> 4)

    # not sure if this is cap bars, zero out if its OOB
    capacity_bars = (d[13] & 0b11110000) >> 4
    if capacity_bars > 12:
        capacity_bars = 0



    range_acon = int(decimal.Decimal(
        (acon*((gids*WH_PER_GID_GEN1)/10000))).__round__(0))
    range_acoff = int(decimal.Decimal(
        (acoff*((gids*WH_PER_GID_GEN1)/10000))).__round__(0))

    chg_time_1 = ((d[2] & 0b00011111) << 6) | ((d[3] & 0b11111100) >> 2)
    chg_time_2 = (d[1] << 3) | ((d[2] & 0b11100000) >> 5)
    chg_time_3 = (d[14] << 3) | ((d[15] & 0b11100000) >> 5)

    if finish_flag:
        charging = False
        quick_charging = False

    # 6.6 kW OBC flag
    obc_flag = (d[15] & 0x02) != 0

    cabin_temp = 0.0

    # ZE1!
    if len(d) == 24:
        temp_data = d[23]
        if temp_data > 0:
            cabin_temp = float(temp_data/2) - 40.0

    return {
        "acon": range_acon,
        "acoff": range_acoff,
        "pluggedin":pluggedin,
        "charging": charging,
        "quick_charging": quick_charging,
        "finish_flag": finish_flag,
        "acstate": acstate,
        "chargebars": chargebars,
        "ignition": ignition,
        "parked": drive_status == 1,
        "direction_forward": drive_status == 4,
        "soc": soc,
        "soc_display": soc_display,
        "soc_display_int": soc_display_int,
        "cabin_temp": cabin_temp,
        "gids": gids,
        "soh": soh,
        "obc_6kw_exist": obc_flag,
        "batt_heat_exist": False,
        "batt_heat_active": False,
        "capacity_bars": capacity_bars,
        "1kw_chg": chg_time_1,
        "3kw_chg": chg_time_2,
        "6kw_chg": chg_time_3
    }, all_li


def make_ack_response(vin: str, dcm_id: str, dest_id: int, src_id: int, prov_type: int, flag: int, value: int) -> bytes:
    acp_msg = bytearray()
    acp_msg += composer.VehDesc(vin=vin, dcm=dcm_id).encode()
    acp_msg += dest_id.to_bytes(1, "little")  # dest ID
    acp_msg += src_id.to_bytes(1, "little")  # src ID
    acp_msg += composer.EVCommandTail(command=0).encode()
    acp_msg += composer.ServiceProvisioning(entries=[composer.ServiceProvisioningService(prov_type, flag == 1, value)]).encode()

    msg = bytearray()
    msg += composer.AppHeader(app_id=0x1d, mcf=3, length=len(acp_msg), special_flag=1).encode()
    msg += acp_msg
    return msg